/**
 * Последний шанс (шаг 68): фишек на долг не хватило — на экране GOOD LUCK, и автомат сходит с ума:
 * крутит сам, без остановки, до LAST_CHANCE_SPINS прокруток подряд; всё, что ляжет на кон, идёт в уплату нехватки.
 * Добрал LAST_CHANCE_SHARE нехватки — выжил (чемодан закрывает долг, счёт −1), не добрал — конец забега.
 * Шанс один за забег, как старая рулетка: вторая нехватка сразу кончает забег.
 * Здесь только числа и маленькие функции; как идут прокрутки — в CollectorScene. Без Phaser — чтобы проверить симуляцией.
 */

/** Сколько прокруток автомат делает сам: игрок ничего не решает, только смотрит на кон. */
export const LAST_CHANCE_SPINS = 10;
/**
 * Какую долю НЕХВАТКИ (долг минус фишки на табло) надо собрать на кону, чтобы выжить.
 * Подобрана на полном забеге при одном шансе за забег; модель совпадает с evaluateLastChance (кровавая прокрутка ×BLOOD_WIN,
 * кровавые черепа жгут табло, у щитов остаток раунда, вес 🎲 по засухе забега).
 * full-run.mjs, 5000 забегов, пять прогонов: 6,87–7,05 долга (медиана 7), 7,5–7,7 мин, выжил 70–71% попыток (до правок модели
 * было 7,08–7,28 долга — кон утекал в следующий раунд). last-chance-sim.mjs, 20 000 проб: 70–71% попыток; в раундах 6–8,
 * где шанс и случается, типовой набор даёт 93 / 79 / 59%. Доля 0,15 — 76%, 0,1 — 80%, 0,02 — 91–92%: 0,2 держит цель 65–75%.
 * Минуты ниже 8 — модель времени: расплата в симуляторе 2,5 с вместо 6. Доля от долга не годилась: на поздних раундах
 * фишек на табло уже много, и 25% долга было не собрать.
 */
export const LAST_CHANCE_SHARE = 0.2;

/** Столько горит GOOD LUCK на экране банкомата (столько же мигают красные огни автомата), прежде чем прокрутки начнутся сами, мс. */
export const GOOD_LUCK_TIME = 1600;

/** Порог: сколько фишек надо собрать на кон, чтобы закрыть нехватку debt − balance. */
export function lastChanceThreshold(debt: number, balance: number): number {
  return Math.ceil(LAST_CHANCE_SHARE * Math.max(0, debt - balance));
}

/** Выжил ли: собрал кон collected, когда до долга не хватало debt − balance. */
export function isLastChanceWon(collected: number, debt: number, balance: number): boolean {
  return collected >= lastChanceThreshold(debt, balance);
}
